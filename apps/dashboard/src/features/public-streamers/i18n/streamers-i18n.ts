/* 모든 로케일을 받도록 값 타입을 string 으로 넓힙니다. */
export type StreamersText = { [Key in keyof (typeof streamersI18n)["ko"]]: string };

/** "{count}개" 같은 자리표시자를 채웁니다. */
export function formatStreamersText(template: string, values: Record<string, string | number>): string {
  return Object.entries(values).reduce(
    (text, [key, value]) => text.replaceAll(`{${key}}`, String(value)),
    template,
  );
}
